export const IDB_DRIVE_OVERRIDES_URL = '/idb-drive-overrides.json';
export const IDB_DRIVE_OVERRIDES_SCHEMA_VERSION = 1;

export type IdbDriveOverridesMap = {
  schemaVersion: typeof IDB_DRIVE_OVERRIDES_SCHEMA_VERSION;
  generatedAt: string;
  overrides: Record<string, string>;
};

const isRecord = (value: unknown): value is Record<string, unknown> => {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
};

const parseIdbDriveOverridesMap = (value: unknown): IdbDriveOverridesMap | null => {
  if (!isRecord(value) || value.schemaVersion !== IDB_DRIVE_OVERRIDES_SCHEMA_VERSION) {
    return null;
  }

  const { generatedAt, overrides } = value;
  if (typeof generatedAt !== 'string' || !isRecord(overrides)) {
    return null;
  }

  for (const [fileName, driveId] of Object.entries(overrides)) {
    if (fileName.length === 0 || typeof driveId !== 'string' || driveId.length === 0) {
      return null;
    }
  }

  return {
    schemaVersion: IDB_DRIVE_OVERRIDES_SCHEMA_VERSION,
    generatedAt,
    overrides: { ...(overrides as Record<string, string>) },
  };
};

/**
 * Mirror filenames whose authoritative drive id cannot be recovered by the T0.4 embedded-id
 * parser (ids containing `__` get truncated). Generated by the bridge mirror tool, served next
 * to the build; any failure turns the feature off and the parser keeps working.
 */
class IdbDriveOverridesStore {
  #overrideByFileName = new Map<string, string>();
  #loadPromise: Promise<void> | undefined;

  ensureLoaded(): Promise<void> {
    this.#loadPromise ??= this.#load();
    return this.#loadPromise;
  }

  async getOverride(fileName: string | null | undefined): Promise<string | null> {
    if (!fileName) {
      return null;
    }

    await this.ensureLoaded();
    return this.#overrideByFileName.get(fileName) ?? null;
  }

  async #load(): Promise<void> {
    try {
      const response = await fetch(IDB_DRIVE_OVERRIDES_URL);
      if (!response.ok) {
        throw new Error(`unexpected status ${response.status}`);
      }

      const map = parseIdbDriveOverridesMap(await response.json());
      if (!map) {
        throw new Error(`unrecognized ${IDB_DRIVE_OVERRIDES_URL} schema`);
      }

      this.#overrideByFileName = new Map(Object.entries(map.overrides));
      console.debug(`[idb] drive-id overrides loaded: ${this.#overrideByFileName.size} entries`);
    } catch (error) {
      console.debug('[idb] drive-id overrides unavailable, falling back to the embedded-id parser', error);
    }
  }
}

export const idbDriveOverrides = new IdbDriveOverridesStore();

export const ensureDriveIdOverridesLoaded = (): Promise<void> => {
  return idbDriveOverrides.ensureLoaded();
};

export const getDriveIdOverride = (fileName: string | null | undefined): Promise<string | null> => {
  return idbDriveOverrides.getOverride(fileName);
};
